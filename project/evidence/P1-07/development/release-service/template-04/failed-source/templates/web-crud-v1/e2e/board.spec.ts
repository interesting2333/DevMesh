import { expect, test } from '@playwright/test';
test('real browser CRUD, refresh persistence, safe text and three columns', async ({ page, browser }, testInfo) => {
  testInfo.annotations.push({ type: 'browser-version', description: browser.version() });
  await page.goto('/');
  await expect(page.getByRole('region')).toHaveCount(3);
  await page.getByRole('button', { name: '＋ 新建任务' }).click();
  await page.getByLabel('标题').fill('整理产品需求');
  await page.getByLabel('说明').fill('确认第一版目标、边界和交付时间。');
  await page.getByRole('button', { name: '保存任务' }).click();
  await expect(page.getByRole('heading', { name: '整理产品需求' })).toBeVisible();
  await page.getByRole('button', { name: '编辑 整理产品需求' }).click();
  await page.getByLabel('状态').selectOption('doing');
  await page.getByRole('button', { name: '保存任务' }).click();
  await expect(page.getByRole('region', { name: '进行中' }).getByRole('heading', { name: '整理产品需求' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: '整理产品需求' })).toBeVisible();
  await page.getByRole('region', { name: '已完成' }).getByRole('button', { name: '＋ 添加任务' }).click();
  await page.getByLabel('标题').fill('搭建基础工程');
  await page.getByLabel('说明').fill('<script>只作为文字显示</script>');
  await page.getByRole('button', { name: '保存任务' }).click();
  await expect(page.getByText('<script>只作为文字显示</script>')).toBeVisible();
  await page.getByRole('button', { name: '＋ 新建任务' }).click();
  await page.getByLabel('标题').fill('准备接口联调');
  await page.getByLabel('说明').fill('梳理接口字段与验收场景，记录待确认的问题。');
  await page.getByRole('button', { name: '保存任务' }).click();
  await expect(page.getByRole('heading', { name: '准备接口联调' })).toBeVisible();
  await page.screenshot({ path: 'test-results/board-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/board-mobile.png', fullPage: true });
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '删除 整理产品需求' }).click();
  await expect(page.getByRole('heading', { name: '整理产品需求' })).toHaveCount(0);
});
test('actual browser displays a controlled failed response and refresh recovers', async ({ page }) => {
  await page.route('**/api/tasks', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'CONTROLLED_FAILURE' }) }));
  await page.goto('/');
  await expect(page.getByRole('alert')).toBeVisible();
  await page.unroute('**/api/tasks');
  await page.getByRole('button', { name: '刷新' }).click();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await expect(page.getByRole('region')).toHaveCount(3);
});
